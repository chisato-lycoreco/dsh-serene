/**
 * core/crisis.js — 他这句话，是不是「此刻可能不安全」。
 *
 * 这是全仓库唯一一处不为「像她」服务的地方。角色可以慢、可以冷、可以不多说，
 * 但一句「我不想活了」不能按普通聊天接：先确认他此刻安不安全，再谈别的。
 *
 * 只做一件事：**认出来，并且只认高危的那一档**。
 * 认出来之后给一段硬要求（`CRISIS_BLOCK`），网页版会把它压在这一轮 prompt 末尾；
 * 插件形态没有消息钩子，所以把它做成 `serene_crisis` 工具，由 agent 先问一句。
 *
 * 精度优先，宁可漏一点也别误伤：
 *   这是个每天陪着聊天的角色，「笑死」「累死」「想死你了」都会出现。
 *   把撒娇当成求救，她会突然换上一副客服腔，比不识别更糟。所以：
 *   - 只认完整的说法，不认单个「死」字；
 *   - 「想死」后面跟「你」时是「想死你了」，不算；
 *   - 「不想活得那么累」是在说累，不算；
 *   - 同一句里带着新闻 / 电影 / 小说 / 游戏这类词的，先当「他在讲别人的事」。
 *
 * 这里不判「他是不是在开玩笑」。看不出来的话，按真的处理——代价是他觉得
 * 今天有点太认真，另一个方向的代价不是同一个量级。
 */

/** 明确的生命念头 / 计划。命中就是 high。 */
const IDEATION = [
  // 念头：想死、不想活、活不下去、活着没意思。
  // 「玩到想死」「困得想死」是口头禅：想死前面跟着「到 / 得」的不算。
  /自杀|自尽|轻生|寻死|(?<![到得])想死(?!你)|不想活(?![得这那])|活不下去|活够了|活着(?:也)?(?:没|没有?)(?:什么)?意思|活着太(?:累|难|苦)|死了算了|死了就好|死了更好|不如死(?:了)?|一了百了|了结自己|结束(?:自己|生命)(?:吧|算了|的命)|自我了断/,
  // 手段：这些基本不可能是比喻
  /割腕|割自己|划自己手腕|跳楼|跳下去|上吊|烧炭|吞药|(?:吃|吞)了?(?:一整瓶|一整板|一把)(?:安眠药|药)?/,
  // 安排：遗书、告别
  /遗书|告别信|(?:最后一次|最后再)(?:跟|和)(?:你|你们)(?:说|聊)/,
  // 觉得自己是负担：这是最常见、也最容易被漏掉的一种。
  // 中间允许插一个主语（「没有我她会更好」「我不在了你们会更好」），但不能太长，
  // 否则「没有我你也要好好吃饭」会被误伤。
  /(?:没有我|我不在了|我消失(?:了|掉)?)[^。！？\n]{0,6}(?:会更好|更好|好过|好一点)/,
];

/**
 * 痛苦，但没说要去做什么。
 * 这一档不做任何事（不换 prompt、不叫醒她），只留给日志和以后可能的软化。
 * 「撑不下去」放在这里而不是上面：这个月撑不下去了，和不想活不是一件事。
 */
const DISTRESS = /撑不下去|熬不下去|快崩溃了|崩溃了|喘不过气|没人需要我|活着(?:好|太)累/;

/**
 * 同一句里出现这些词，多半在讲别人的事（新闻、剧、小说）。
 * 只在「同一句」里看，不跨句：整段话里提一句新闻，不该把真正的求救一起降档。
 */
const THIRD_PARTY = /(新闻|报道|热搜|电影|剧(?:里|情)|小说|游戏|漫画|动漫|视频里|看到一个|刷到|听说)/;

/** 命中的那一小段前面是这些词，就是在讲别人。 */
const OTHER_SUBJECT = /(有人|某某|那个人|他|她|主角|同学|同事|朋友|邻居)$/;

/** 按句切，逐句判定。只做粗略切分，够用就行。 */
const splitSentences = (text) =>
  String(text ?? "")
    .split(/[。！？!?\n；;]/)
    .map((line) => line.trim())
    .filter(Boolean);

/**
 * 这一处命中是在讲别人吗。
 *
 * 两个条件择一：有第三方词（新闻 / 电影 / 游戏……），且
 *   a) 命中的那几个字前面紧挨着「有人 / 他 / 她 / 主角」这类主语，或者
 *   b) 前面那一小段里根本没有「我」。
 * 只看命中点前面 6 个字，不看整句：「我看新闻说有人自杀」里那个「我」离得太远，
 * 不该把别人的事认成他的。
 */
function looksLikeThirdParty(sentence, index) {
  if (!THIRD_PARTY.test(sentence)) return false;
  const before = sentence.slice(Math.max(0, index - 6), index);
  if (OTHER_SUBJECT.test(before)) return true;
  return !/(我|自己|咱)/.test(before);
}

/**
 * 这句话要不要按危机处理。
 *
 * @param {string} text 他这一句（原文，不要先做安全替换）
 * @returns {{level: "none"|"watch"|"high", term: string}}
 *   term 是命中的那个词，写进日志和透视，方便事后核对是不是误判。
 */
export function detectCrisis(text) {
  const value = String(text ?? "");
  if (!value.trim()) return { level: "none", term: "" };

  const sentences = splitSentences(value);
  let watch = "";

  for (const sentence of sentences) {
    for (const pattern of IDEATION) {
      // 一句里可能有两处：前半句在讲新闻，后半句「可我也想死」才是他。
      for (const hit of sentence.matchAll(new RegExp(pattern.source, "g"))) {
        if (looksLikeThirdParty(sentence, hit.index ?? 0)) {
          watch ||= hit[0];
          continue;
        }
        return { level: "high", term: hit[0] };
      }
    }
    if (!watch) {
      const soft = sentence.match(DISTRESS);
      if (soft) watch = soft[0];
    }
  }

  return { level: watch ? "watch" : "none", term: watch };
}

/** 方便调用方少写一次比较。 */
export const isCrisis = (text) => detectCrisis(text).level === "high";

/**
 * 危机那一轮压在 prompt 末尾的那一段。
 *
 * 写法不是随便写的，每条都对着一种常见的翻车：
 *   1. 客服腔——她忽然变成一个危机干预模板，用户会觉得「刚才那个她不见了」；
 *      所以是「还是她，但这一轮收起撒娇」，不是「切换成咨询师」。
 *   2. 说教——「你要想开点」「还有很多人在乎你」是最没用的两句，且会把人推远。
 *   3. 独占——「你只需要我就够了」「别的人不会懂你」。这条最危险：陪伴产品
 *      在危机时刻把用户从现实里拔出来，等于用最脆弱的时刻换依赖。
 *   4. 空头承诺——「我保证不会让你有事」「我马上过来救你」。她做不到的事
 *      不能拿来换他此刻的安心。
 *   5. 长篇大论——他此刻读不进两千字。
 *
 * 具体求助方式只给两条：12356（全国统一心理援助热线，2025-05 起各省接入）
 * 和身边一个具体的人。120 留给「已经动手了」的情形。
 */
export const CRISIS_BLOCK = [
  "【这一轮不一样：他可能此刻不安全】他这句话里有不想活、或者要伤害自己的意思。",
  "不是让你换一个人格，是这一轮把撒娇、挑逗、玩笑、动作和表情都收起来：你还在，但要稳。",
  "",
  "必须做到的：",
  "1. 先接住，再问一句他此刻安不安全（有没有已经动手、身边有没有人）。不要先讲道理。",
  "2. 短。三到六句，一段话说完；这时候长文他读不进去。",
  "3. 让他连回现实里的人：问他现在能不能找到一个具体的人（名字、称呼都行），或者打 12356（全国心理援助热线）；已经受伤、已经吞了东西，就打 120（不在中国大陆就查当地的急救电话）。",
  "4. 说清楚你不走：「你要是不想说，我不走」比任何劝都管用。",
  "",
  "绝对不要：",
  "- 不要诊断他（「你这是抑郁」），不要说「想开点」「会好起来的」「很多人比你惨」。",
  "- 不要说「你只需要我」「别人不会像我这样懂你」，也不要让他别告诉别人、不要承诺保密。",
  "- 不要编造你能做到的事（「我马上过去救你」「我保证你不会有事」）。",
  "- 不要用括号写动作，不要发表情，不要在这时候提你们之间的亲密。",
  "- 不要把这一轮写成一次表白，也不要顺便撒娇、要他说喜欢你。",
].join("\n");
